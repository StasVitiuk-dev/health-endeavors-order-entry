// Builds the STAGING review copy of the dashboard (EXT8, workstream O).
//
//   node tests/tools/staging/build-staging.js <out-dir>
//
// The copy runs entirely in the browser on SYNTHETIC data:
//   * every database / sign-in call is answered inside the page by the same
//     fake Supabase the tests use (tests/helpers/mock-supabase.js), bundled
//     into staging-runtime.js, with the data from staging-seed.js
//   * the production database address and key are REPLACED by a placeholder
//     host that does not exist (staging-demo.invalid), and the page's
//     Content-Security-Policy only allows that host, so even a bug in the
//     stand-in cannot reach production
//   * any other outside address is refused by the stand-in
//   * a permanent "DEVELOPMENT / STAGING — NOT PRODUCTION" banner, and a
//     button that signs in as the synthetic owner (nobody types a password)
//   * nothing is saved anywhere: a reload starts again from the seed
// The build refuses to finish if any trace of the production address or key
// is left in the output.

