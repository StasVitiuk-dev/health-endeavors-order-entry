// EXT15: inline style="" attributes → generated utility classes, so the owner
// page can run with style-src 'self' (no 'unsafe-inline').
//
//   node tests/tools/inline-styles.js            → report (count, unique, dynamic)
//   node tests/tools/inline-styles.js --write    → rewrite the files + regenerate
//                                                  the utility block in the CSS
//   node tests/tools/inline-styles.js --check    → exit 1 if any static inline style
//                                                  is left or the CSS block is stale
//
// Each declaration becomes one class (u-<property>-<value>), e.g.
// style="font-size:11px;color:var(--muted)" → class="u-fs-11 u-c-muted".
// Utilities are !important so they keep the precedence the inline style had over
// ordinary rules, EXCEPT display: the page shows and hides elements by writing
// element.style.display from JavaScript, which must keep winning.
// Dynamic values (`${...}`) are not touched; they are converted by hand.
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const FILES = ['owner-login.html', 'assets/owner-login-app.js'];
const CSS = path.join(ROOT, 'assets', 'owner-login.css');
const BEGIN = '/* @@ EXT15 utilities: generated by tests/tools/inline-styles.js from the former inline styles; do not edit by hand @@ */';
const END = '/* @@ end utilities @@ */';
const NOT_IMPORTANT = new Set(['display']);

const ABBR = {
  'font-size': 'fs', 'font-weight': 'fw', 'font-family': 'ff', 'font-style': 'fst', color: 'c', background: 'bg', 'background-color': 'bgc',
  margin: 'm', 'margin-top': 'mt', 'margin-bottom': 'mb', 'margin-left': 'ml', 'margin-right': 'mr',
  padding: 'p', 'padding-top': 'pt', 'padding-bottom': 'pb', 'padding-left': 'pl', 'padding-right': 'pr',
  display: 'd', 'flex-direction': 'fd', 'flex-wrap': 'fwr', flex: 'flex', gap: 'gap', 'align-items': 'ai', 'align-self': 'as', 'justify-content': 'jc',
  width: 'w', 'min-width': 'minw', 'max-width': 'maxw', height: 'h', 'min-height': 'minh', 'max-height': 'maxh',
  border: 'b', 'border-top': 'bt', 'border-bottom': 'bb', 'border-radius': 'br', 'border-left': 'bl',
  'text-align': 'ta', 'white-space': 'ws', 'line-height': 'lh', 'letter-spacing': 'ls', 'text-transform': 'tt', 'text-decoration': 'td',
  overflow: 'ov', 'overflow-x': 'ovx', 'overflow-y': 'ovy', 'word-break': 'wb', 'overflow-wrap': 'ow', cursor: 'cur', resize: 'rs', opacity: 'op',
  'vertical-align': 'va', position: 'pos', 'grid-template-columns': 'gtc', 'list-style': 'lst', 'box-sizing': 'bxs',
};
function slug(v) {
  return v.trim().toLowerCase()
    .replace(/var\(--([a-z0-9-]+)\)/g, '$1').replace(/#([0-9a-f]{3,8})/g, 'x$1').replace(/(\d)\.(\d)/g, '$1p$2')
    .replace(/-(\d)/g, 'n$1').replace(/%/g, 'pct').replace(/px\b/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'x';
}
function parseDecls(s) {
  return s.split(';').map(d => d.trim()).filter(Boolean).map(d => {
    const i = d.indexOf(':');
    return [d.slice(0, i).trim().toLowerCase(), d.slice(i + 1).trim()];
  });
}
const className = ([p, v]) => 'u-' + (ABBR[p] || p.replace(/[^a-z0-9]+/g, '')) + '-' + slug(v);

// Every style="…" in a file, with whether it is static.
function findStyles(text) {
  const out = [];
  for (const m of text.matchAll(/style="([^"]*)"/g)) out.push({ index: m.index, full: m[0], value: m[1], dynamic: m[1].includes('${') });
  return out;
}

function collect() {
  const all = [];
  for (const f of FILES) for (const s of findStyles(fs.readFileSync(path.join(ROOT, f), 'utf8'))) all.push({ file: f, ...s });
  return all;
}

// Rewrite one tag: drop style="…", add the classes to its class attribute (or a new one).
function rewrite(text, classesFor) {
  return text.replace(/<([a-zA-Z][a-zA-Z0-9-]*)((?:[^<>"']|"[^"]*"|'[^']*')*?)\sstyle="([^"$]*)"((?:[^<>"']|"[^"]*"|'[^']*')*)>/g, (all, tag, before, style, after) => {
    const cls = classesFor(style);
    const attrs = before + after;
    const m = /\sclass="([^"]*)"/.exec(attrs);
    if (m) return '<' + tag + attrs.replace(m[0], ' class="' + (m[1] + ' ' + cls.join(' ')).trim() + '"') + '>';
    return '<' + tag + before + ' class="' + cls.join(' ') + '"' + after + '>';
  });
}

function cssBlock(decls) {
  const lines = [...decls.entries()].sort((a, b) => a[0].localeCompare(b[0]))
    .map(([cls, [p, v]]) => `.${cls}{${p}:${v}${NOT_IMPORTANT.has(p) ? '' : ' !important'}}`);
  return BEGIN + '\n' + lines.join('\n') + '\n' + END + '\n';
}

function run(mode) {
  const styles = collect();
  const statics = styles.filter(s => !s.dynamic);
  const decls = new Map();
  const classesFor = style => parseDecls(style).map(d => { const c = className(d); const prev = decls.get(c); if (prev && (prev[0] !== d[0] || prev[1] !== d[1])) throw new Error('class name clash: ' + c); decls.set(c, d); return c; });
  for (const s of statics) classesFor(s.value);
  const css = fs.readFileSync(CSS, 'utf8');
  const hasBlock = css.includes(BEGIN);
  if (mode === '--write') {
    for (const f of FILES) {
      const p = path.join(ROOT, f);
      const before = fs.readFileSync(p, 'utf8');
      const after = rewrite(before, classesFor);
      fs.writeFileSync(p, after);
    }
    // keep classes from earlier runs (their inline sources are gone now)
    if (hasBlock) for (const line of css.slice(css.indexOf(BEGIN), css.indexOf(END)).split('\n')) {
      const m = /^\.(u-[a-z0-9-]+)\{([a-z-]+):(.*?)( !important)?\}$/.exec(line);
      if (m && !decls.has(m[1])) decls.set(m[1], [m[2], m[3]]);
    }
    const block = cssBlock(decls);
    const next = hasBlock ? css.slice(0, css.indexOf(BEGIN)) + block + css.slice(css.indexOf(END) + END.length + 1) : css.replace(/\s*$/, '\n\n') + block;
    fs.writeFileSync(CSS, next);
    const left = collect();
    console.log('rewritten; inline styles left:', left.length, '(dynamic:', left.filter(s => s.dynamic).length + ')', 'utility classes:', decls.size);
    return left;
  }
  if (mode === '--check') {
    const problems = statics.map(s => `${s.file}: static inline ${s.full}`);
    if (problems.length) { problems.forEach(p => console.log(p)); process.exitCode = 1; } else console.log('OK: no static inline styles in', FILES.join(', '));
    return problems;
  }
  console.log(JSON.stringify({ total: styles.length, static: statics.length, dynamic: styles.filter(s => s.dynamic).length, uniqueStatic: new Set(statics.map(s => s.value)).size, utilityClasses: decls.size, byFile: Object.fromEntries(FILES.map(f => [f, styles.filter(s => s.file === f).length])) }, null, 1));
  return styles;
}
if (require.main === module) run(process.argv[2]);
module.exports = { run, parseDecls, className, findStyles, rewrite, FILES, BEGIN, END };
