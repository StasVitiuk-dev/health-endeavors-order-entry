// Generates the machine-checked part of docs/ops/SALES_INVENTORY.md from the
// code: the Sales & Growth engine modules, the pages wired behind the flag, and
// the sales spec files. A freshness spec (sales-inventory-ext20j.spec.js) fails
// if the committed doc drifts from this output.
//   node tests/tools/sales-inventory.js            → print
//   node tests/tools/sales-inventory.js --write     → update the doc
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const DOC = path.join(ROOT, 'docs', 'ops', 'SALES_INVENTORY.md');
const BEGIN = '<!-- @@ generated by tests/tools/sales-inventory.js: do not edit by hand @@ -->';
const END = '<!-- @@ end generated @@ -->';

function salesModules() {
  return fs.readdirSync(path.join(ROOT, 'assets', 'sales')).filter(f => /^he-sales-.*\.js$/.test(f)).sort();
}
function loadedModules() {
  const html = fs.readFileSync(path.join(ROOT, 'owner-login.html'), 'utf8');
  return [...html.matchAll(/assets\/sales\/(he-sales-[a-z]+\.js)\?v=/g)].map(m => m[1]).sort();
}
function salesPages() {
  const cfg = fs.readFileSync(path.join(ROOT, 'assets', 'app', 'he-config.js'), 'utf8');
  const block = /const SALES_GROWTH_GROUP = \{[\s\S]*?pages: \[([\s\S]*?)\]\}/.exec(cfg);
  if (!block) return [];
  return [...block[1].matchAll(/\{ id: '([a-zA-Z]+)',\s*label: '([^']+)'/g)].map(m => ({ id: m[1], label: m[2] }));
}
function salesSpecs() {
  return fs.readdirSync(path.join(ROOT, 'tests', 'specs')).filter(f => /^sales-.*\.spec\.js$/.test(f)).sort();
}

function render() {
  const mods = salesModules(), loaded = loadedModules(), pages = salesPages(), specs = salesSpecs();
  const L = [];
  L.push(BEGIN);
  L.push('', `**Engine modules:** ${mods.length} · **loaded on the page:** ${loaded.length} · **pages (flag-gated):** ${pages.length} · **spec files:** ${specs.length}`, '');
  L.push('### Engine modules (`assets/sales/`)', '');
  for (const m of mods) L.push(`- \`${m}\`${loaded.includes(m) ? ' *(loaded)*' : ''}`);
  L.push('', '### Pages (only visible when the Sales & Growth flag is ON)', '');
  for (const p of pages) L.push(`- \`${p.id}\` — ${p.label}`);
  L.push('', '### Spec files (`tests/specs/`)', '');
  for (const s of specs) L.push(`- \`${s}\``);
  L.push('', END);
  return L.join('\n');
}

if (require.main === module) {
  const out = render();
  if (process.argv.includes('--write')) {
    let doc;
    const header = '# Sales & Growth — generated inventory\n\nStatus: CURRENT (branch work, not merged). Regenerate with `node tests/tools/sales-inventory.js --write`.\nThis lists the Sales & Growth engine modules, flag-gated pages, and spec files. Every item is synthetic/advisory and OFF by default; see `SALES_GROWTH_AND_WHOLESALE_SYSTEM.md`.\n\n';
    if (fs.existsSync(DOC) && fs.readFileSync(DOC, 'utf8').includes(BEGIN)) {
      doc = fs.readFileSync(DOC, 'utf8');
      doc = doc.slice(0, doc.indexOf(BEGIN)) + out + doc.slice(doc.indexOf(END) + END.length);
    } else {
      doc = header + out + '\n';
    }
    fs.writeFileSync(DOC, doc);
    console.log('wrote', path.relative(ROOT, DOC));
  } else console.log(out);
}
module.exports = { render, BEGIN, END, DOC, salesModules, loadedModules, salesPages, salesSpecs };
