// EXT15: writes the generated part of docs/ops/APPLICATION_MODULE_MAP_EXT15.md
// from the code (module files, the program's create calls, the graph), so the
// map cannot drift. tests/specs/modules-ext15.spec.js fails if it is stale.
//   node tests/tools/module-map.js           → print
//   node tests/tools/module-map.js --write   → update the doc between the markers
const fs = require('fs');
const path = require('path');
const { check } = require('./app-modules');
const { analyse, summary } = require('./app-graph');
const ROOT = path.join(__dirname, '..', '..');
const DOC = path.join(ROOT, 'docs', 'ops', 'APPLICATION_MODULE_MAP_EXT15.md');
const BEGIN = '<!-- @@ generated by tests/tools/module-map.js: do not edit by hand @@ -->';
const END = '<!-- @@ end generated @@ -->';

function render() {
  const { creates, edges, mods } = check();
  const appText = fs.readFileSync(path.join(ROOT, 'assets', 'owner-login-app.js'), 'utf8');
  const lines = [];
  lines.push('| # | Module | What it holds | Lines | Inputs (from) | Exports |', '|---|---|---|---|---|---|');
  creates.forEach((c, i) => {
    const m = mods.find(x => x.name === c.name);
    const text = fs.readFileSync(m.file, 'utf8');
    const what = (/— (.*)\n/.exec(text) || [])[1] || '';
    const from = {};
    for (const n of m.needs) { const e = edges.find(x => x[0] === c.name && x[2] === n); const src = e ? e[1] : (/^[A-Z_]+$/.test(n) && ['SUPABASE_URL', 'SUPABASE_ANON_KEY'].includes(n) ? 'page constant' : 'helpers / program'); (from[src] = from[src] || []).push(n); }
    const inputs = Object.entries(from).map(([k, v]) => `${k}: ${v.length}`).join(', ') || '—';
    lines.push(`| ${i + 1} | \`${c.name}\` | ${what} | ${text.split('\n').length} | ${inputs} | ${m.exports.length} |`);
  });
  const s = summary(analyse());
  lines.push('', `Program file after extraction: \`assets/owner-login-app.js\` ${s.lines.toLocaleString('en-US')} lines, ${s.bytes.toLocaleString('en-US')} bytes; ${s.topLevelFunctions} top-level functions; ${s.mutableTopLevel} mutable top-level variables (${s.sharedMutable} shared).`);
  lines.push('', 'Dependency graph (module ← modules it takes inputs from; the program creates them top to bottom):', '', '```');
  for (const c of creates) lines.push(`${c.name.padEnd(14)} ← ${[...new Set(edges.filter(e => e[0] === c.name).map(e => e[1]))].join(', ') || '(none)'}`);
  lines.push('```');
  return BEGIN + '\n' + lines.join('\n') + '\n' + END;
}
if (require.main === module) {
  const out = render();
  if (process.argv.includes('--write')) {
    const doc = fs.readFileSync(DOC, 'utf8');
    if (!doc.includes(BEGIN)) throw new Error('markers missing in ' + DOC);
    fs.writeFileSync(DOC, doc.slice(0, doc.indexOf(BEGIN)) + out + doc.slice(doc.indexOf(END) + END.length));
    console.log('updated', path.relative(ROOT, DOC));
  } else console.log(out);
}
module.exports = { render, BEGIN, END, DOC };
